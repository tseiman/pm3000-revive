#include "pm3000_acme_certificate.h"
#include "pm3000_acme_crypto.h"

#include <stdio.h>
#include <string.h>

static int read_fixture(const char *path, unsigned char *buffer,
                        unsigned int capacity, unsigned int *length)
{
    FILE *file = fopen(path, "rb");
    size_t amount;
    if (file == NULL) return -1;
    amount = fread(buffer, 1U, capacity, file);
    if (ferror(file) || !feof(file) || fclose(file) != 0) return -1;
    *length = (unsigned int)amount;
    return 0;
}

static int append_bytes(unsigned char *output, unsigned int capacity,
                        unsigned int *length, const unsigned char *value,
                        unsigned int value_length)
{
    if (value_length > capacity - *length) return -1;
    memcpy(output + *length, value, value_length);
    *length += value_length;
    return 0;
}

static int append_text(unsigned char *output, unsigned int capacity,
                       unsigned int *length, const char *value)
{
    return append_bytes(output, capacity, length,
                        (const unsigned char *)value,
                        (unsigned int)strlen(value));
}

static int expect_ca_bundle(const char *name, const unsigned char *bundle,
                            unsigned int length, int accepted)
{
    int result = pm3000_acme_certificate_validate_ca_bundle(bundle, length);
    if ((result == PM3000_ACME_CERTIFICATE_OK) != accepted) {
        fprintf(stderr, "CA bundle case failed: %s (result=%d)\n", name, result);
        return -1;
    }
    return 0;
}

int main(void)
{
    struct pm3000_acme_key server_key = {0};
    struct pm3000_acme_key wrong_key = {0};
    static const char *valid_names[] = {"acme.example.test", "localhost"};
    static const char *partial_names[] = {"acme.example.test"};
    static const char *invalid_names[] = {"other.example.test"};
    unsigned char certificate[65537U];
    unsigned char bundle[65537U];
    unsigned char private_key[65537U];
    unsigned int certificate_length = 0U;
    unsigned int bundle_length = 0U;
    unsigned int private_key_length = 0U;
    if (pm3000_acme_crypto_key_load(
            "tests/fixtures/tls/server-key.pem", &server_key) !=
            PM3000_ACME_CRYPTO_OK ||
        pm3000_acme_crypto_key_load(
            "tests/fixtures/account-test-key.pem", &wrong_key) !=
            PM3000_ACME_CRYPTO_OK ||
        read_fixture("tests/fixtures/tls/ca.pem", certificate,
                     sizeof(certificate), &certificate_length) != 0 ||
        read_fixture("tests/fixtures/account-test-key.pem", private_key,
                     sizeof(private_key), &private_key_length) != 0) return 2;
    if (expect_ca_bundle("certificate only", certificate, certificate_length, 1) != 0 ||
        expect_ca_bundle("private key only", private_key, private_key_length, 0) != 0)
        return 1;

    bundle_length = 0U;
    if (append_text(bundle, sizeof(bundle), &bundle_length,
                    "Operator supplied trust anchors\nGenerated by Example PKI\n") != 0 ||
        append_bytes(bundle, sizeof(bundle), &bundle_length, certificate,
                     certificate_length) != 0 ||
        append_text(bundle, sizeof(bundle), &bundle_length,
                    "\nSecond certificate follows\r\n") != 0 ||
        append_bytes(bundle, sizeof(bundle), &bundle_length, certificate,
                     certificate_length) != 0 ||
        append_text(bundle, sizeof(bundle), &bundle_length,
                    "Trailing human comment without newline") != 0 ||
        expect_ca_bundle("comments before between and after certificates",
                         bundle, bundle_length, 1) != 0)
        return 1;

    bundle_length = 0U;
    if (append_bytes(bundle, sizeof(bundle), &bundle_length, certificate,
                     certificate_length) != 0 ||
        append_bytes(bundle, sizeof(bundle), &bundle_length, private_key,
                     private_key_length) != 0 ||
        expect_ca_bundle("private key after certificate", bundle,
                         bundle_length, 0) != 0)
        return 1;

#define REJECT_SUFFIX(case_name, suffix) do { \
        bundle_length = 0U; \
        if (append_bytes(bundle, sizeof(bundle), &bundle_length, certificate, \
                         certificate_length) != 0 || \
            append_text(bundle, sizeof(bundle), &bundle_length, (suffix)) != 0 || \
            expect_ca_bundle((case_name), bundle, bundle_length, 0) != 0) \
            return 1; \
    } while (0)
    REJECT_SUFFIX("CSR after certificate",
                  "-----BEGIN CERTIFICATE REQUEST-----\nQUJD\n-----END CERTIFICATE REQUEST-----\n");
    REJECT_SUFFIX("unknown PEM object after certificate",
                  "-----BEGIN EXAMPLE OBJECT-----\nQUJD\n-----END EXAMPLE OBJECT-----\n");
    REJECT_SUFFIX("ambiguous begin marker",
                  "-----BEGIN CERTIFICATE----- trailing text\n");
    REJECT_SUFFIX("ambiguous end marker",
                  "human text -----END CERTIFICATE-----\n");
#undef REJECT_SUFFIX

    if (expect_ca_bundle("empty certificate block",
                         (const unsigned char *)
                             "-----BEGIN CERTIFICATE-----\n"
                             "-----END CERTIFICATE-----\n",
                         (unsigned int)strlen(
                             "-----BEGIN CERTIFICATE-----\n"
                             "-----END CERTIFICATE-----\n"), 0) != 0 ||
        expect_ca_bundle("malformed certificate payload",
                         (const unsigned char *)
                             "-----BEGIN CERTIFICATE-----\nQUJD\n"
                             "-----END CERTIFICATE-----\n",
                         (unsigned int)strlen(
                             "-----BEGIN CERTIFICATE-----\nQUJD\n"
                             "-----END CERTIFICATE-----\n"), 0) != 0 ||
        expect_ca_bundle("junk inside base64",
                         (const unsigned char *)
                             "-----BEGIN CERTIFICATE-----\nQU!JD\n"
                             "-----END CERTIFICATE-----\n",
                         (unsigned int)strlen(
                             "-----BEGIN CERTIFICATE-----\nQU!JD\n"
                             "-----END CERTIFICATE-----\n"), 0) != 0)
        return 1;

    bundle_length = 0U;
    {
        unsigned int index;
        for (index = 0U; index < 10U; ++index)
            if (append_bytes(bundle, sizeof(bundle), &bundle_length, certificate,
                             certificate_length) != 0)
                return 2;
    }
    if (expect_ca_bundle("too many certificates", bundle, bundle_length, 0) != 0)
        return 1;
    memset(bundle, 'x', sizeof(bundle));
    if (expect_ca_bundle("oversized bundle", bundle, sizeof(bundle), 0) != 0)
        return 1;
    if (pm3000_acme_certificate_validate(
            "tests/fixtures/tls/issued.pem", "tests/fixtures/tls/ca.pem",
            &server_key, valid_names, 2U) != PM3000_ACME_CERTIFICATE_OK ||
        pm3000_acme_certificate_validate(
            "tests/fixtures/tls/issued.pem", "tests/fixtures/tls/ca.pem",
            &server_key, partial_names, 1U) == PM3000_ACME_CERTIFICATE_OK ||
        pm3000_acme_certificate_validate(
            "tests/fixtures/tls/issued.pem", "tests/fixtures/tls/ca.pem",
            &server_key, invalid_names, 1U) == PM3000_ACME_CERTIFICATE_OK ||
        pm3000_acme_certificate_validate(
            "tests/fixtures/tls/issued.pem", "tests/fixtures/tls/ca.pem",
            &wrong_key, valid_names, 2U) == PM3000_ACME_CERTIFICATE_OK) {
        fprintf(stderr, "certificate validation contract failed\n");
        pm3000_acme_crypto_key_free(&wrong_key);
        pm3000_acme_crypto_key_free(&server_key);
        return 1;
    }
    pm3000_acme_crypto_key_free(&wrong_key);
    pm3000_acme_crypto_key_free(&server_key);
    puts("certificate.tests.complete=yes");
    return 0;
}
